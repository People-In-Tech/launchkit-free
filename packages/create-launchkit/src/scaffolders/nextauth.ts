/**
 * NextAuth v5 scaffolder
 *
 * Creates 3 foundational auth files for NextAuth v5 (Auth.js):
 *   1. apps/web/lib/auth.ts           — NextAuth configuration
 *   2. apps/web/middleware.ts         — route protection middleware
 *   3. apps/web/app/api/auth/[...nextauth]/route.ts — API route handler
 *
 * Also generates a comprehensive Claude Code prompt for migrating the
 * rest of the app from Clerk to NextAuth v5.
 */

import fs from "node:fs";
import path from "node:path";
import chalk from "chalk";

export interface ScaffoldResult {
  ok: boolean;
  message: string;
}

// ── Template: apps/web/lib/auth.ts ────────────────────────────────────────────

const AUTH_CONFIG_TEMPLATE = `/**
 * NextAuth v5 (Auth.js) configuration
 * Generated by create-launchkit
 *
 * Docs: https://authjs.dev/getting-started
 *
 * Add more providers at https://authjs.dev/getting-started/authentication/oauth
 */
import NextAuth from "next-auth";
import GitHub from "next-auth/providers/github";
import Google from "next-auth/providers/google";
import Resend from "next-auth/providers/resend";
import { DrizzleAdapter } from "@auth/drizzle-adapter";
import { db } from "@launchkit/database";

export const { handlers, signIn, signOut, auth } = NextAuth({
  adapter: DrizzleAdapter(db),
  providers: [
    GitHub({
      clientId: process.env.AUTH_GITHUB_ID,
      clientSecret: process.env.AUTH_GITHUB_SECRET,
    }),
    Google({
      clientId: process.env.AUTH_GOOGLE_ID,
      clientSecret: process.env.AUTH_GOOGLE_SECRET,
    }),
    Resend({
      apiKey: process.env.RESEND_API_KEY,
      from: process.env.EMAIL_FROM ?? "noreply@yourdomain.com",
    }),
  ],
  callbacks: {
    session({ session, user }) {
      session.user.id = user.id;
      return session;
    },
  },
  pages: {
    signIn: "/auth/sign-in",
    signUp: "/auth/sign-up",
    error: "/auth/error",
  },
});
`;

// ── Template: apps/web/middleware.ts ─────────────────────────────────────────

const MIDDLEWARE_TEMPLATE = `/**
 * NextAuth v5 middleware — route protection
 * Generated by create-launchkit
 *
 * Protects all routes under /dashboard, /settings, /portal, /admin.
 * Public routes (landing page, blog, auth pages) are passed through.
 */
import { auth } from "@/lib/auth";
import { NextResponse } from "next/server";
import type { NextRequest } from "next/server";

const PUBLIC_ROUTES = [
  "/",
  "/pricing",
  "/blog",
  "/changelog",
  "/auth/sign-in",
  "/auth/sign-up",
  "/auth/error",
  "/api/webhooks",
];

export default auth((req) => {
  const { pathname } = req.nextUrl;

  // Allow public routes
  const isPublic = PUBLIC_ROUTES.some(
    (route) => pathname === route || pathname.startsWith(route + "/")
  );
  if (isPublic) return NextResponse.next();

  // Redirect unauthenticated users to sign-in
  if (!req.auth) {
    const signInUrl = new URL("/auth/sign-in", req.url);
    signInUrl.searchParams.set("callbackUrl", pathname);
    return NextResponse.redirect(signInUrl);
  }

  return NextResponse.next();
});

export const config = {
  matcher: [
    "/((?!_next/static|_next/image|favicon.ico|.*\\\\.(?:svg|png|jpg|jpeg|gif|webp)$).*)",
  ],
};
`;

// ── Template: apps/web/app/api/auth/[...nextauth]/route.ts ───────────────────

const ROUTE_TEMPLATE = `/**
 * NextAuth v5 API route handler
 * Generated by create-launchkit
 */
import { handlers } from "@/lib/auth";

export const { GET, POST } = handlers;
`;

