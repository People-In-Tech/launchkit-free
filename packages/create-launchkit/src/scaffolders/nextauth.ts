// ── Main scaffolder ──────────────────────────────────────────────────────────

export function applyNextAuthScaffold(projectRoot: string): ScaffoldResult[] {
  const results: ScaffoldResult[] = [];
  const webRoot = path.join(projectRoot, "apps/web");

  // ── 1. lib/auth.ts ─────────────────────────────────────────────────────────
  const authPath = path.join(webRoot, "lib/auth.ts");
  try {
    // Back up existing file if present
    if (fs.existsSync(authPath)) {
      fs.writeFileSync(authPath + ".clerk.bak", fs.readFileSync(authPath, "utf-8"), "utf-8");
      results.push({ ok: true, message: "Backed up existing lib/auth.ts → lib/auth.ts.clerk.bak" });
    }
    fs.mkdirSync(path.dirname(authPath), { recursive: true });
    fs.writeFileSync(authPath, AUTH_CONFIG_TEMPLATE, "utf-8");
    results.push({ ok: true, message: "Created apps/web/lib/auth.ts" });
  } catch (err) {
    results.push({ ok: false, message: `Failed to write lib/auth.ts: ${err instanceof Error ? err.message : String(err)}` });
  }

  // ── 2. middleware.ts ───────────────────────────────────────────────────────
  const middlewarePath = path.join(webRoot, "middleware.ts");
  try {
    if (fs.existsSync(middlewarePath)) {
      fs.writeFileSync(middlewarePath + ".clerk.bak", fs.readFileSync(middlewarePath, "utf-8"), "utf-8");
      results.push({ ok: true, message: "Backed up existing middleware.ts → middleware.ts.clerk.bak" });
    }
    fs.writeFileSync(middlewarePath, MIDDLEWARE_TEMPLATE, "utf-8");
    results.push({ ok: true, message: "Created apps/web/middleware.ts" });
  } catch (err) {
    results.push({ ok: false, message: `Failed to write middleware.ts: ${err instanceof Error ? err.message : String(err)}` });
  }

  // ── 3. app/api/auth/[...nextauth]/route.ts ────────────────────────────────
  const routeDir = path.join(webRoot, "app/api/auth/[...nextauth]");
  const routePath = path.join(routeDir, "route.ts");
  try {
    fs.mkdirSync(routeDir, { recursive: true });
    fs.writeFileSync(routePath, ROUTE_TEMPLATE, "utf-8");
    results.push({ ok: true, message: "Created apps/web/app/api/auth/[...nextauth]/route.ts" });
  } catch (err) {
    results.push({ ok: false, message: `Failed to write auth route: ${err instanceof Error ? err.message : String(err)}` });
  }

  // ── 4. Write Claude prompt to file ────────────────────────────────────────
  const claudePromptPath = path.join(projectRoot, "NEXTAUTH_MIGRATION_PROMPT.md");
  try {
    fs.writeFileSync(claudePromptPath, generateNextAuthClaudePrompt(), "utf-8");
    results.push({ ok: true, message: "Created NEXTAUTH_MIGRATION_PROMPT.md — paste this into Claude Code to finish the migration" });
  } catch (err) {
    results.push({ ok: false, message: `Failed to write Claude prompt: ${err instanceof Error ? err.message : String(err)}` });
  }

  return results;
}

/** Print NextAuth scaffold results to console */
export function printNextAuthResults(results: ScaffoldResult[]): void {
  for (const result of results) {
    if (result.ok) {
      console.log(`  ${chalk.green("✔")} ${result.message}`);
    } else {
      console.log(`  ${chalk.yellow("⚠")} ${result.message}`);
    }
  }
}
