function writeDynamicEnvFile(
  projectRoot: string,
  stack: StackSelection,
  envValues: Record<string, string>
): void {
  const envLocalPath = path.join(projectRoot, "apps/web/.env.local");
  const lines: string[] = [
    "# Generated by create-launchkit",
    "# https://getlaunchkit.app",
    "",
  ];

  // ── Database ───────────────────────────────────────────────────────────────
  switch (stack.database) {
    case "neon":
      lines.push(
        "# ── Database (Neon) ────────────────────────────────────────────────────────",
        `DATABASE_URL=${envValues["DATABASE_URL"] ?? ""}`,
        ""
      );
      break;
    case "supabase":
      lines.push(
        "# ── Database (Supabase) ────────────────────────────────────────────────────",
        `SUPABASE_URL=${envValues["SUPABASE_URL"] ?? ""}`,
        `SUPABASE_ANON_KEY=${envValues["SUPABASE_ANON_KEY"] ?? ""}`,
        `SUPABASE_SERVICE_ROLE_KEY=${envValues["SUPABASE_SERVICE_ROLE_KEY"] ?? ""}`,
        "# Direct connection URL for Drizzle migrations (not the pooler URL):",
        `SUPABASE_DB_URL=${envValues["SUPABASE_DB_URL"] ?? ""}`,
        ""
      );
      break;
  }

  // ── Auth ──────────────────────────────────────────────────────────────────
  switch (stack.auth) {
    case "clerk":
      lines.push(
        "# ── Auth (Clerk) ───────────────────────────────────────────────────────────",
        `NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY=${envValues["NEXT_PUBLIC_CLERK_PUBLISHABLE_KEY"] ?? ""}`,
        `CLERK_SECRET_KEY=${envValues["CLERK_SECRET_KEY"] ?? ""}`,
        `CLERK_WEBHOOK_SECRET=${envValues["CLERK_WEBHOOK_SECRET"] ?? ""}`,
        "NEXT_PUBLIC_CLERK_SIGN_IN_URL=/auth/sign-in",
        "NEXT_PUBLIC_CLERK_SIGN_UP_URL=/auth/sign-up",
        "NEXT_PUBLIC_CLERK_AFTER_SIGN_IN_URL=/dashboard",
        "NEXT_PUBLIC_CLERK_AFTER_SIGN_UP_URL=/dashboard",
        ""
      );
      break;
    case "supabase":
      lines.push(
        "# ── Auth (Supabase — uses SUPABASE_URL and SUPABASE_ANON_KEY above) ─────────",
        ""
      );
      break;
    case "nextauth":
      lines.push(
        "# ── Auth (NextAuth v5) ──────────────────────────────────────────────────────",
        `AUTH_SECRET=${envValues["AUTH_SECRET"] ?? ""}`,
        `AUTH_GITHUB_ID=${envValues["AUTH_GITHUB_ID"] ?? ""}`,
        `AUTH_GITHUB_SECRET=${envValues["AUTH_GITHUB_SECRET"] ?? ""}`,
        `AUTH_GOOGLE_ID=${envValues["AUTH_GOOGLE_ID"] ?? ""}`,
        `AUTH_GOOGLE_SECRET=${envValues["AUTH_GOOGLE_SECRET"] ?? ""}`,
        "NEXTAUTH_URL=http://localhost:3000",
        ""
      );
      break;
  }

  // ── Payments ──────────────────────────────────────────────────────────────
  switch (stack.payments) {
    case "stripe":
      lines.push(
        "# ── Payments (Stripe) ──────────────────────────────────────────────────────",
        `STRIPE_SECRET_KEY=${envValues["STRIPE_SECRET_KEY"] ?? ""}`,
        `NEXT_PUBLIC_STRIPE_PUBLISHABLE_KEY=${envValues["NEXT_PUBLIC_STRIPE_PUBLISHABLE_KEY"] ?? ""}`,
        `STRIPE_WEBHOOK_SECRET=${envValues["STRIPE_WEBHOOK_SECRET"] ?? ""}`,
        "STRIPE_SOLO_PRICE_ID=",
        "STRIPE_TEAMS_PRICE_ID=",
        ""
      );
      break;
    case "lemonsqueezy":
      lines.push(
        "# ── Payments (Lemon Squeezy) ────────────────────────────────────────────────",
        `LEMONSQUEEZY_API_KEY=${envValues["LEMONSQUEEZY_API_KEY"] ?? ""}`,
        `LEMONSQUEEZY_STORE_ID=${envValues["LEMONSQUEEZY_STORE_ID"] ?? ""}`,
        `LEMONSQUEEZY_WEBHOOK_SECRET=${envValues["LEMONSQUEEZY_WEBHOOK_SECRET"] ?? ""}`,
        ""
      );
      break;
    case "paddle":
      lines.push(
        "# ── Payments (Paddle) ──────────────────────────────────────────────────────",
        `PADDLE_API_KEY=${envValues["PADDLE_API_KEY"] ?? ""}`,
        `PADDLE_WEBHOOK_SECRET=${envValues["PADDLE_WEBHOOK_SECRET"] ?? ""}`,
        "PADDLE_ENVIRONMENT=sandbox",
        ""
      );
      break;
  }

  // ── AI provider ───────────────────────────────────────────────────────────
  const aiMeta = AI_PROVIDERS[stack.aiProvider];
  lines.push(`# ── AI (${aiMeta.label}) ${"─".repeat(Math.max(0, 68 - aiMeta.label.length))}`);
  const aiKey = getAIEnvVar(stack.aiProvider);
  lines.push(
    `${aiKey.key}=${envValues[aiKey.key] ?? ""}`,
    `AI_DEFAULT_PROVIDER=${stack.aiProvider}`,
    `AI_DEFAULT_MODEL=${aiMeta.defaultModel ?? ""}`,
    ""
  );

  // ── Storage ───────────────────────────────────────────────────────────────
  lines.push(
    "# ── Storage ────────────────────────────────────────────────────────────────",
    `STORAGE_PROVIDER=${stack.storageProvider}`,
    `BLOB_READ_WRITE_TOKEN=${envValues["BLOB_READ_WRITE_TOKEN"] ?? ""}`,
    ""
  );

  // ── Email ─────────────────────────────────────────────────────────────────
  if (stack.email) {
    lines.push(
      `# ── Email (${stack.email === "resend" ? "Resend" : "Postmark"}) ─────────────────────────────────────────────────────────────`,
      stack.email === "resend"
        ? `RESEND_API_KEY=${envValues["RESEND_API_KEY"] ?? ""}`
        : `POSTMARK_API_TOKEN=${envValues["POSTMARK_API_TOKEN"] ?? ""}`,
      `EMAIL_FROM=My App <hello@yourdomain.com>`,
      ""
    );
  }

  // ── PostHog ───────────────────────────────────────────────────────────────
  lines.push(
    "# ── Analytics (PostHog) ────────────────────────────────────────────────────",
    `NEXT_PUBLIC_POSTHOG_KEY=${envValues["NEXT_PUBLIC_POSTHOG_KEY"] ?? ""}`,
    "NEXT_PUBLIC_POSTHOG_HOST=https://app.posthog.com",
    ""
  );

  // ── App ───────────────────────────────────────────────────────────────────
  lines.push(
    "# ── App ────────────────────────────────────────────────────────────────────",
    `NEXT_PUBLIC_APP_URL=${envValues["NEXT_PUBLIC_APP_URL"] ?? "http://localhost:3000"}`,
    `NEXT_PUBLIC_APP_NAME=My SaaS App`,
    ""
  );

  // Ensure directory exists (apps/web may not be the CWD)
  const envDir = path.dirname(envLocalPath);
  if (!fs.existsSync(envDir)) {
    // Fallback: write to project root
    const rootEnvPath = path.join(projectRoot, ".env.local");
    fs.writeFileSync(rootEnvPath, lines.join("\n") + "\n", "utf-8");
    return;
  }

  fs.writeFileSync(envLocalPath, lines.join("\n") + "\n", "utf-8");
}

// ---------------------------------------------------------------------------
// Command runner
// ---------------------------------------------------------------------------

function runCommand(
  cmd: string,
  args: string[],
  cwd: string
): Promise<{ ok: boolean; output: string }> {
  return new Promise((resolve) => {
    let output = "";
    const proc = spawn(cmd, args, { cwd, shell: true });
    proc.stdout.on("data", (d: Buffer) => { output += d.toString(); });
    proc.stderr.on("data", (d: Buffer) => { output += d.toString(); });
    proc.on("close", (code) => { resolve({ ok: code === 0, output }); });
  });
}

// ---------------------------------------------------------------------------
// Parse CLI flags
// ---------------------------------------------------------------------------

interface CLIFlags {
  db?: string;
  auth?: string;
  payments?: string;
  help?: boolean;
}

function parseFlags(): CLIFlags {
  const flags: CLIFlags = {};
  for (const arg of process.argv.slice(2)) {
    if (arg === "--help" || arg === "-h") { flags.help = true; continue; }
    const [key, val] = arg.replace(/^--/, "").split("=");
    if (key === "db" || key === "database") flags.db = val;
    if (key === "auth") flags.auth = val;
    if (key === "payments" || key === "billing") flags.payments = val;
  }
  return flags;
}

