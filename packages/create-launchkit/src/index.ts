/**
 * Walks up from startDir looking for a launchkit.config.ts or
 * a package.json whose `name` includes "launchkit".
 * Returns the root directory if found, null otherwise.
 */
function findLaunchKitRoot(startDir: string): string | null {
  let dir = startDir;
  for (let i = 0; i < 5; i++) {
    if (fs.existsSync(path.join(dir, "launchkit.config.ts"))) {
      return dir;
    }
    // Check root package.json name
    const pkgPath = path.join(dir, "package.json");
    if (fs.existsSync(pkgPath)) {
      try {
        const pkg = JSON.parse(fs.readFileSync(pkgPath, "utf-8")) as {
          name?: string;
        };
        if (pkg.name && /launchkit/i.test(pkg.name)) {
          return dir;
        }
      } catch {
        // ignore parse errors
      }
    }
    const parent = path.dirname(dir);
    if (parent === dir) break; // filesystem root
    dir = parent;
  }
  return null;
}

